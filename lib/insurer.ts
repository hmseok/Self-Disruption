const INSURER_ALIASES: Array<[string, string[]]> = [
  ['삼성', ['삼성화재', '삼성']],
  ['현대', ['현대해상', '현대', '현대해']],
  ['디비', ['디비손해', 'db손해', 'db', '디비']],
  ['케이비', ['케이비손해', 'kb손해', 'kb', '케이비']],
  ['한화', ['한화손해', '한화']],
  ['하나', ['하나손해', '하나']],
  ['캐롯', ['캐롯손해', '캐롯']],
  ['메리츠', ['메리츠화재', '메리츠']],
  ['흥국', ['흥국화재', '흥국']],
  ['롯데', ['롯데손해', '롯데']],
  ['엠지', ['엠지손해', 'mg손해', 'mg', '엠지']],
  ['악사', ['악사손해', 'axa', '악사']],
  ['렌공', ['전국렌터카공제', '렌터카공제', '렌공']],
  ['화물공제', ['화물공제', '화물자동차공제']],
  ['정비대차', ['정비대차']],
  ['현금대차', ['현금대차', '현금']],
]

export function normInsurer(s: unknown): string | null {
  const t = String(s || '').toLowerCase().replace(/[\s\-_()·.,*㈜]+/g, '')
  if (!t) return null
  for (const [key, aliases] of INSURER_ALIASES) {
    if (aliases.some(a => t.includes(a))) return key
  }
  return null
}
